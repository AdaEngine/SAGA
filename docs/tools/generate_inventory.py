#!/usr/bin/env python3
"""Deterministic baseline inventory extraction; no implementation or conformance claim."""
import collections, hashlib, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC_REV = '4e829b310ba7381034b93b974eb1a6aabfb464f7'
CTS_REV = 'd116bcccd1833369fa3715a6df503c0dd9b0d7fa'
WGPU_REV = 'a55352911bb26a1b33bc8d5fc03bdebb0a967f5a'

def extract():
    rows = []
    for domain in ['webgpu', 'wgsl']:
        text = (ROOT / 'sources' / f'{domain}-spec.bs').read_text()
        # Explicit heading anchors only: includes nonnormative chapters, marked for review.
        for m in re.finditer(r'^(#{1,6})\s+(.+?)\s+#+\s+\{#([^}]+)\}', text, re.M):
            level, title, anchor = m.groups()
            rows.append(dict(id=f'{domain.upper()}-SEC-{anchor}', domain=domain,
                kind='section', title=title, anchor=anchor, level=len(level),
                source=f'sources/{domain}-spec.bs', revision=SPEC_REV,
                normative='review-required', implementation='not-started', verification='not-run',
                owner=owner(domain,anchor), test_source=tests(domain), evidence=[]))
        if domain == 'webgpu':
            # Parse declarations from IDL scripts, not examples/prose. Preserve full member text.
            for block in re.findall(r'<script\s+type=[\"\']?idl[\"\']?[^>]*>(.*?)</script>', text, re.S|re.I):
                for m in re.finditer(r'\b(interface(?:\s+mixin)?|dictionary|enum|namespace)\s+(\w+)\s*(?::\s*\w+\s*)?\{(.*?)\};',block,re.S):
                    kind,name,body=m.groups()
                    rows.append(dict(id=f'API-{name}',domain=domain,kind=kind,title=name,
                        source='sources/webgpu-spec.bs',revision=SPEC_REV,token=name,
                        normative='idl',implementation='not-started',verification='not-run',
                        owner=owner(domain,name.lower()),test_source=tests(domain),evidence=[],
                        members=[re.sub(r'\s+',' ',x).strip() for x in (body.split(',') if kind=='enum' else body.split(';')) if x.strip()]))
    merged = {}
    for row in rows:
        if row["id"] in merged:
            merged[row["id"]]["members"].extend(row["members"])
        else:
            merged[row["id"]] = row
    return list(merged.values())

def tests(domain):
    return 'src/webgpu/shader' if domain=='wgsl' else 'src/webgpu/api'

def owner(domain,a):
    if domain=='wgsl':
        return 'SAGA-6' if any(x in a for x in ['memory','builtin','execution','floating','subgroup','collective']) else 'SAGA-5'
    if any(x in a for x in ['canvas','error','device','query','queries','limit','feature','telemetry']): return 'SAGA-9'
    if any(x in a for x in ['shader','compilation']): return 'SAGA-5'
    if any(x in a for x in ['pipeline','pass','bind','render','blend','vertex','fragment','primitive','multisample','draw','bundle']): return 'SAGA-8'
    if any(x in a for x in ['buffer','texture','sampler','command','queue','copy','synchronization','resource']): return 'SAGA-7'
    return 'SAGA-3'

def main():
    rows=extract()
    ids=[r['id'] for r in rows]; assert len(ids)==len(set(ids))
    manifest=dict(schema=1,scope='coarse baseline, not an exhaustive normative assertion inventory',
        spec_revision=SPEC_REV,cts_revision=CTS_REV,reference_revision=WGPU_REV,items=rows)
    (ROOT/'inventory.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
    counts=collections.Counter(r['domain']+'-'+('idl' if r['kind']!='section' else 'section') for r in rows)
    content=['# API / WGSL inventory','', 'Generated by `python3 docs/tools/generate_inventory.py`. Baseline source/license: [provenance](provenance.md).',
       '', 'All rows: implementation **not-started**, verification **not-run**, evidence empty. Owner = proposed workstream, not a board reassignment.',
       'Each section is a review unit, not one normative requirement. Examples/intro/appendices remain review-required; IDL declarations include enums, namespaces, mixins and dictionaries.',
       'Full declaration member text is retained in [inventory.json](inventory.json); overloads remain within their declaration. Inherited members, typedefs, includes and inline HTML headings need assertion-level refinement before a full-coverage claim.',
       '', '## Counts','']
    content += [f'- {k}: {v}' for k,v in sorted(counts.items())]
    content += ['', '## Register','', '| Stable ID | Source / topic | Owner | Planned test source |','|---|---|---|---|']
    for r in rows:
        ident=r['id']; domain=r['domain']; base='https://gpuweb.github.io/gpuweb/'+('wgsl/' if domain=='wgsl' else '')
        link=base+'#'+r['anchor'] if r['kind']=='section' else f'https://github.com/gpuweb/gpuweb/blob/{SPEC_REV}/spec/index.bs'
        title=r['title'].replace('|',' / ')
        content.append(f'| <a id="{ident}"></a>`{ident}` | [{title}]({link}) | {r["owner"]} | `{r["test_source"]}` |')
    (ROOT/'inventory.md').write_text('\n'.join(content)+'\n')
    print(json.dumps(dict(items=len(rows),counts=dict(counts)),indent=2))
if __name__=='__main__': main()
